"""Turn real benchmark output into a traceable reStructuredText fragment (PR 5).

Consumes only files written by the benchmark itself and never trains anything:

* ``<comparison>/summary.json`` and ``<comparison>/runs/*.json``  (``polynomial_cl_bench.runner``)
* ``<results>/tuning_<algorithm>.json``                           (``polynomial_cl_bench.tune``)
* ``<results>/selection_<algorithm>.json``                        (``polynomial_cl_bench.selection``)

and writes ``paper/generated/benchmark_results.rst``. Every number in the output is computed
here from those files, and the SHA-256 of every source file is printed in the fragment, so a
number in the paper can be traced to the file that produced it. Hand-written text never
contains a result; it includes this fragment.

    python tools/build_benchmark_results.py --results results \\
        --comparison results/tuned_comparison --out paper/generated/benchmark_results.rst
"""

from __future__ import annotations

import argparse
import hashlib
import json
import statistics
import sys
from pathlib import Path

ALGORITHMS = ("polynomial_cl", "er_mlp")
OBJECTIVES = ("max_accuracy", "min_forgetting", "min_time", "best_tradeoff")


class MissingInput(Exception):
    """A required result file is absent: nothing is written rather than a partial fragment."""


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load(path: Path) -> dict:
    if not path.is_file():
        raise MissingInput(f"missing required result file: {path}")
    return json.loads(path.read_text())


def pct(x, digits=2):
    return "n/a" if x is None else f"{100 * x:.{digits}f}"


def num(x, digits=1):
    return "n/a" if x is None else f"{x:.{digits}f}"


def mean_std(values):
    """(mean, sample std) of the non-null values; std is None for fewer than two values."""
    v = [x for x in values if x is not None]
    if not v:
        return None, None
    return statistics.fmean(v), (statistics.stdev(v) if len(v) > 1 else None)


def cell(mean, std, scale=1.0, digits=2):
    if mean is None:
        return "n/a"
    text = f"{scale * mean:.{digits}f}"
    return text if std is None else f"{text} ± {scale * std:.{digits}f}"


def list_table(header, rows, widths=None):
    lines = [".. list-table::", "   :header-rows: 1"]
    if widths:
        lines.append("   :widths: " + " ".join(str(w) for w in widths))
    lines.append("")
    for row in [header, *rows]:
        for i, item in enumerate(row):
            lines.append(("   * - " if i == 0 else "     - ") + str(item))
    return "\n".join(lines)


def completed_runs(comparison: Path):
    """Records of completed runs, grouped by algorithm label."""
    groups: dict[str, list[dict]] = {}
    for path in sorted((comparison / "runs").glob("*.json")):
        record = json.loads(path.read_text())
        if record.get("status") != "completed":
            continue
        groups.setdefault(record["algorithm"]["label"], []).append(record)
    return groups


def grid_edges(selection: dict, tuning: dict):
    """Report, per tunable key, whether the selected value is at an end of the searched grid."""
    chosen = tuning["selected_config"]
    notes = []
    for key in chosen:
        values = [g[key] for g in tuning["grid"]]
        flat = [json.dumps(v) for v in values]
        distinct = sorted(set(flat), key=lambda s: json.loads(s))
        if len(distinct) < 2:
            continue
        here = json.dumps(chosen[key])
        if here == distinct[0]:
            notes.append(f"``{key}`` = {chosen[key]} is the *smallest* value searched")
        elif here == distinct[-1]:
            notes.append(f"``{key}`` = {chosen[key]} is the *largest* value searched")
    return notes


def build(results: Path, comparison: Path) -> str:
    summary = load(comparison / "summary.json")
    manifest = load(comparison / "manifest.json")
    tuning = {a: load(results / f"tuning_{a_file(a)}.json") for a in ALGORITHMS}
    selection = {a: load(results / f"selection_{a_file(a)}.json") for a in ALGORITHMS}
    runs = completed_runs(comparison)

    protocol = summary["protocol"]
    env = manifest["environment"]
    validation = summary["validation"]
    out: list[str] = []
    add = out.append

    add(
        ".. Generated by tools/build_benchmark_results.py from benchmark output. Do not edit."
    )
    add("")
    add("Provenance of these results")
    add("~" * 27)
    add("")
    sources = [
        ("comparison summary", comparison / "summary.json"),
        ("comparison manifest", comparison / "manifest.json"),
    ]
    for a in ALGORITHMS:
        sources.append((f"tuning, {a}", results / f"tuning_{a_file(a)}.json"))
        sources.append((f"selection, {a}", results / f"selection_{a_file(a)}.json"))
    add(
        list_table(
            ["Source", "File", "SHA-256"],
            [[name, f"``{p.name}``", f"``{sha256(p)}``"] for name, p in sources],
            [22, 28, 50],
        )
    )
    add("")
    add(
        f"Protocol ``{protocol['name']}`` version {protocol['version']}, evaluated on the "
        f"**{protocol['evaluation_split']}** split. Run mode: ``{env['run_mode']}``. "
        f"Python {env['python_version']}, NumPy {env['numpy_version']}, "
        f"{env['cpu_count']} CPU(s), BLAS thread variables "
        f"{', '.join(f'{k}={v}' for k, v in env['thread_env'].items() if v is not None)}."
    )
    add("")
    add(
        f"Publishable according to the benchmark's own validation: **{validation['publishable']}**."
    )
    if validation["publication_blockers"]:
        add("")
        add("Blockers reported by the benchmark:")
        add("")
        for blocker in validation["publication_blockers"]:
            add(f"* {blocker}")
    add("")

    # ---------------------------------------------------------------- tuned comparison
    add("Tuned comparison")
    add("~" * 16)
    add("")
    seeds = summary["seeds"]
    rows = []
    for label, group in runs.items():
        wall = mean_std([r["resources"]["wall_time_seconds"] for r in group])
        mem = mean_std([r["resources"]["peak_memory_mb"] for r in group])
        params = {r["resources"]["n_parameters"] for r in group}
        agg = summary["aggregate"]["algorithms"][label]["metrics"]
        acc, forg = agg["final_accuracy"], agg["mean_forgetting"]
        rows.append(
            [
                f"``{label}``",
                f"{len(group)} / {len(seeds)}",
                cell(acc["mean"], acc["std"], 100),
                f"[{pct(acc['ci95'][0])}, {pct(acc['ci95'][1])}]",
                cell(forg["mean"], forg["std"], 100),
                cell(*wall, digits=1),
                cell(*mem, digits=0),
                ", ".join(str(p) for p in sorted(params)),
            ]
        )
    add(
        list_table(
            [
                "Algorithm",
                "Seeds completed",
                "Final accuracy (%)",
                "95% CI (%)",
                "Forgetting (%)",
                "Wall time (s)",
                "Peak memory (MB)",
                "Parameters",
            ],
            rows,
        )
    )
    add("")
    add(
        f"Seeds {', '.join(str(s) for s in seeds)}; mean ± sample standard deviation. Seeds vary "
        "initialisation, sampling and replay selection, not the data split. Wall time is "
        "measured by the runner around the whole run and includes in-loop evaluation and, for "
        "the polynomial method, the construction of its features inside the run."
    )
    add("")

    paired = summary["aggregate"]["paired_comparisons"]
    prow = []
    for p in paired:
        ci = p.get("ci95_mean_difference")
        prow.append(
            [
                f"``{p['a']}`` − ``{p['b']}``",
                p["metric"],
                p["n_pairs"] if "n_pairs" in p else p.get("pairs"),
                f"{100 * p['mean_difference']:+.2f}"
                if "mean_difference" in p
                else "n/a",
                "n/a" if not ci else f"[{100 * ci[0]:+.2f}, {100 * ci[1]:+.2f}]",
                f"{p.get('a_higher', 'n/a')} / {p.get('b_higher', 'n/a')} / {p.get('ties', 'n/a')}",
            ]
        )
    add(
        list_table(
            [
                "Pair",
                "Metric",
                "Pairs",
                "Mean difference (points)",
                "95% CI (points)",
                "a higher / b higher / tie",
            ],
            prow,
        )
    )
    add("")
    add(
        "Differences are descriptive: with this few pairs the interval assumes roughly normal "
        "differences and should be treated as tentative."
    )
    add("")

    # ---------------------------------------------------------------- reproducibility
    add("Reproducibility check")
    add("~" * 21)
    add("")
    add(
        list_table(
            [
                "Algorithm",
                "Seed",
                "Re-run status",
                "Bit-identical",
                "Max abs. difference",
            ],
            [
                [
                    f"``{r['label']}``",
                    r["seed"],
                    r["rerun_status"],
                    r["exact_match"],
                    r["max_abs_difference"],
                ]
                for r in summary["reproducibility"]
            ],
        )
    )
    add("")
    add(
        "Same machine, same environment, fresh process. This is a repeat, not an independent "
        "reproduction on other hardware."
    )
    add("")

    # ---------------------------------------------------------------- tuning
    add("Hyper-parameters selected on validation")
    add("~" * 39)
    add("")
    trows = []
    for a in ALGORITHMS:
        t = tuning[a]
        cfg = next(c for c in t["configs"] if c["config_index"] == t["selected_index"])
        trows.append(
            [
                f"``{a}``",
                f"``{json.dumps(t['selected_config'], sort_keys=True)}``",
                t["selected_index"],
                pct(cfg["mean_final_accuracy"]),
                pct(cfg["mean_forgetting"]),
                f"{len(t['grid'])} configurations × {len(t['selection_seeds'])} seeds "
                f"({', '.join(str(s) for s in t['selection_seeds'])})",
            ]
        )
    add(
        list_table(
            [
                "Algorithm",
                "Selected",
                "Grid index",
                "Validation accuracy (%)",
                "Validation forgetting (%)",
                "Search",
            ],
            trows,
        )
    )
    add("")
    for a in ALGORITHMS:
        notes = grid_edges(selection[a], tuning[a])
        if notes:
            add(
                f"* ``{a}``: "
                + "; ".join(notes)
                + ". The optimum may lie outside the searched "
                "grid, so the selection is the best of the grid, not necessarily the best "
                "configuration."
            )
    add("")
    add(
        "Selection used the validation hold-out only (10% of the training data), with seeds "
        "disjoint from the evaluation seeds."
    )
    add("")

    # ---------------------------------------------------------------- four objectives
    add("Four model-selection objectives (validation)")
    add("~" * 43)
    add("")
    for a in ALGORITHMS:
        sel = selection[a]
        add(f"``{a}``, accuracy floor {sel['accuracy_floor']}:")
        add("")
        orows = []
        for key in OBJECTIVES:
            w = sel["winners"][key]
            orows.append(_objective_row(key, w, tuning[a]))
        for key in ("min_forgetting", "min_time", "best_tradeoff"):
            w = sel["floor_winners"].get(key)
            if w is not None:
                orows.append(_objective_row(f"{key} (with floor)", w, tuning[a]))
        add(
            list_table(
                [
                    "Objective",
                    "Configuration",
                    "Accuracy (%)",
                    "Forgetting (%)",
                    "Time (s)",
                ],
                orows,
            )
        )
        add("")
    add(
        "Without the floor, the forgetting objective is won by a model that barely learns; the "
        "floor rows are the meaningful ones for forgetting and time."
    )
    add("")
    return "\n".join(out) + "\n"


def a_file(algorithm: str) -> str:
    """File-name stem used by the tuning and selection outputs."""
    return "polynomial" if algorithm == "polynomial_cl" else algorithm


def _objective_row(name, winner, tuning):
    cfg = tuning["grid"][winner["candidate_id"]]
    v = winner["values"]
    return [
        name,
        f"``{json.dumps(cfg, sort_keys=True)}``",
        pct(v["accuracy"]),
        pct(v["forgetting"]),
        num(v["time_seconds"], 2),
    ]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--results", type=Path, required=True)
    parser.add_argument("--comparison", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        text = build(args.results, args.comparison)
    except MissingInput as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
